#!/usr/bin/env bash
set -euo pipefail

# This is the real VRT for the Docker/Ansible reproduction: the frame is
# captured from OBS in the provisioned container publishing the actual
# vigilant-fiesta game page to the in-network MediaMTX RTMPS endpoint. It
# replaces the 1x1 placeholder under tests/vrt/.
project_root=$(cd "$(dirname "$0")/.." && pwd)
cd "${project_root}"

vrt_dir=${1:-tests/vrt-rtmps}
baseline_dir="${vrt_dir}/baseline"
ssim_threshold=${VRT_SSIM_THRESHOLD:-0.80}

# H.264 compression and browser-source font rasterisation add small per-frame
# differences even for the same static game page, so compare structurally
# instead of comparing PNG bytes.
compare_with_baseline() {
  local actual=$1
  local baseline=$2
  local score

  score=$(ffmpeg -hide_banner -nostdin -i "${actual}" -i "${baseline}" \
    -lavfi ssim -f null - 2>&1 \
    | sed -n 's/.*SSIM .*All:\([0-9.]*\).*/\1/p' | tail -n 1)
  if [ -z "${score}" ]; then
    echo "VRT: could not compute SSIM for ${actual}" >&2
    return 1
  fi

  echo "VRT: SSIM(${actual}, ${baseline}) = ${score} (threshold ${ssim_threshold})"
  awk -v score="${score}" -v threshold="${ssim_threshold}" \
    'BEGIN { exit !(score >= threshold) }'
}

status=0
cases_executed=0

# A case that silently leaves the previous capture in place must not be able to
# pass by comparing a stale image with the baseline.
run_marker=$(mktemp)
touch -d '1 minute ago' "${run_marker}"
trap 'rm -f "${run_marker}"' EXIT

for case_file in "${vrt_dir}"/*; do
  [ -f "${case_file}" ] || continue
  case "${case_file}" in
    *.png|*.jpg|*.jpeg|*.html) continue ;;
  esac
  if [ -x "${case_file}" ]; then
    "${case_file}" || status=1
    cases_executed=$((cases_executed + 1))
  elif [[ "${case_file}" == *.sh ]]; then
    bash "${case_file}" || status=1
    cases_executed=$((cases_executed + 1))
  else
    continue
  fi

  base=$(basename "${case_file}")
  stem=${base%.*}
  actual="${vrt_dir}/${stem}.png"
  baseline="${baseline_dir}/${stem}.png"

  if [ ! -f "${actual}" ]; then
    echo "VRT: missing actual output for ${stem} (${actual})" >&2
    status=1
    continue
  fi
  if [ -z "$(find "${actual}" -newer "${run_marker}" -print -quit 2>/dev/null)" ]; then
    echo "VRT: ${actual} was not regenerated by ${base}" >&2
    status=1
    continue
  fi
  if [ ! -f "${baseline}" ]; then
    echo "VRT: missing committed baseline for ${stem} (${baseline})" >&2
    status=1
    continue
  fi

  compare_with_baseline "${actual}" "${baseline}" || status=1
done

# An empty case directory must never be reported as a successful VRT run.
if [ "${cases_executed}" -eq 0 ]; then
  echo "VRT: no RTMPS VRT case was executed in ${vrt_dir}" >&2
  status=1
fi

exit "${status}"
